@Service(Service.Level.PROJECT)
class MetalTranspilerService(private val project: Project) {
    
    companion object {
        fun getInstance(project: Project): MetalTranspilerService {
            return project.getService(MetalTranspilerService::class.java)
        }
    }
    
    fun transpileToSPIRV(metalFile: VirtualFile) {
        transpile(metalFile, "spvasm", "SPIR-V") { content ->
            convertMetalToSPIRV(content, metalFile.name)
        }
    }

    fun transpileToHLSL(metalFile: VirtualFile) {
        transpile(metalFile, "hlsl", "HLSL") { content ->
            convertMetalToHLSL(content, metalFile.name)
        }
    }

    fun transpileToWGSL(metalFile: VirtualFile) {
        transpile(metalFile, "wgsl", "WGSL") { content ->
            convertMetalToWGSL(content, metalFile.name)
        }
    }

    private fun convertMetalToSPIRV(source: String, fileName: String): String {
        val sb = StringBuilder()
        sb.appendLine("; SPIR-V assembly transpiled from Metal source: $fileName")
        sb.appendLine("; Generated by Metal Shader Support Plugin")
        sb.appendLine()
        sb.appendLine("OpCapability Shader")
        sb.appendLine("OpMemoryModel Logical GLSL450")

        val entryPoints = detectEntryPoints(source)
        entryPoints.forEach { ep ->
            val executionModel = when (ep.type) {
                "vertex" -> "Vertex"
                "fragment" -> "Fragment"
                "kernel" -> "GLCompute"
                else -> "GLCompute"
            }
            sb.appendLine("OpEntryPoint $executionModel %${ep.name} \"${ep.name}\"")
            if (ep.type == "fragment") {
                sb.appendLine("OpExecutionMode %${ep.name} OriginUpperLeft")
            }
            if (ep.type == "kernel") {
                sb.appendLine("OpExecutionMode %${ep.name} LocalSize 1 1 1")
            }
        }

        sb.appendLine()
        sb.appendLine("; Type declarations")
        sb.appendLine("%void = OpTypeVoid")
        sb.appendLine("%float = OpTypeFloat 32")
        sb.appendLine("%int = OpTypeInt 32 1")
        sb.appendLine("%uint = OpTypeInt 32 0")
        sb.appendLine("%v2float = OpTypeVector %float 2")
        sb.appendLine("%v3float = OpTypeVector %float 3")
        sb.appendLine("%v4float = OpTypeVector %float 4")
        sb.appendLine("%v3uint = OpTypeVector %uint 3")
        sb.appendLine("%mat4v4float = OpTypeMatrix %v4float 4")

        val structs = detectStructs(source)
        structs.forEach { struct ->
            sb.appendLine()
            sb.appendLine("; Struct: ${struct.name}")
            val memberTypes = struct.members.joinToString(" ") { mapMetalTypeToSPIRV(it.type) }
            sb.appendLine("%${struct.name} = OpTypeStruct $memberTypes")
            struct.members.forEachIndexed { index, member ->
                sb.appendLine("OpMemberName %${struct.name} $index \"${member.name}\"")
            }
        }

        sb.appendLine()
        entryPoints.forEach { ep ->
            sb.appendLine("; Entry point: ${ep.name}")
            sb.appendLine("%func_${ep.name} = OpTypeFunction %void")
            sb.appendLine("%${ep.name} = OpFunction %void None %func_${ep.name}")
            sb.appendLine("%label_${ep.name} = OpLabel")
            sb.appendLine("OpReturn")
            sb.appendLine("OpFunctionEnd")
        }

        return sb.toString()
    }

    private fun convertMetalToHLSL(source: String, fileName: String): String {
        var result = "// HLSL transpiled from Metal source: $fileName\n"
        result += "// Generated by Metal Shader Support Plugin\n\n"

        val structs = detectStructs(source)
        structs.forEach { struct ->
            result += "struct ${struct.name} {\n"
            struct.members.forEach { member ->
                val hlslType = mapMetalTypeToHLSL(member.type)
                val semantic = mapMetalAttributeToHLSLSemantic(member.attribute)
                val semanticStr = if (semantic.isNotEmpty()) " : $semantic" else ""
                result += "    $hlslType ${member.name}$semanticStr;\n"
            }
            result += "};\n\n"
        }

        var body = source
        body = applyHLSLTypeReplacements(body)
        body = applyHLSLFunctionReplacements(body)

        val entryPoints = detectEntryPoints(source)
        entryPoints.forEach { ep ->
            when (ep.type) {
                "vertex" -> {
                    result += "// Vertex shader: ${ep.name}\n"
                    result += "${ep.returnType.let { mapMetalTypeToHLSL(it) }} ${ep.name}(${convertParamsToHLSL(ep.params)}) {\n"
                    result += extractAndConvertBody(source, ep.name, "hlsl")
                    result += "}\n\n"
                }
                "fragment" -> {
                    result += "// Pixel shader: ${ep.name}\n"
                    result += "${ep.returnType.let { mapMetalTypeToHLSL(it) }} ${ep.name}(${convertParamsToHLSL(ep.params)}) : SV_Target {\n"
                    result += extractAndConvertBody(source, ep.name, "hlsl")
                    result += "}\n\n"
                }
                "kernel" -> {
                    result += "// Compute shader: ${ep.name}\n"
                    result += "[numthreads(1, 1, 1)]\n"
                    result += "void ${ep.name}(${convertParamsToHLSL(ep.params)}) {\n"
                    result += extractAndConvertBody(source, ep.name, "hlsl")
                    result += "}\n\n"
                }
            }
        }

        return result
    }

    private fun convertMetalToWGSL(source: String, fileName: String): String {
        var result = "// WGSL transpiled from Metal source: $fileName\n"
        result += "// Generated by Metal Shader Support Plugin\n\n"

        val structs = detectStructs(source)
        structs.forEach { struct ->
            result += "struct ${struct.name} {\n"
            struct.members.forEachIndexed { index, member ->
                val wgslType = mapMetalTypeToWGSL(member.type)
                val builtin = mapMetalAttributeToWGSLBuiltin(member.attribute)
                val annotation = if (builtin.isNotEmpty()) "$builtin " else "@location($index) "
                val comma = if (index < struct.members.size - 1) "," else ""
                result += "    $annotation${member.name}: $wgslType$comma\n"
            }
            result += "}\n\n"
        }

        val bufferBindings = detectBufferBindings(source)
        bufferBindings.forEachIndexed { index, binding ->
            val wgslType = mapMetalTypeToWGSL(binding.type)
            val accessMode = if (binding.isConst) "read" else "read_write"
            result += "@group(0) @binding($index) var<storage, $accessMode> ${binding.name}: $wgslType;\n"
        }
        if (bufferBindings.isNotEmpty()) result += "\n"

        val entryPoints = detectEntryPoints(source)
        entryPoints.forEach { ep ->
            when (ep.type) {
                "vertex" -> {
                    val wgslReturn = mapMetalTypeToWGSL(ep.returnType)
                    result += "@vertex\nfn ${ep.name}(${convertParamsToWGSL(ep.params)}) -> $wgslReturn {\n"
                    result += extractAndConvertBody(source, ep.name, "wgsl")
                    result += "}\n\n"
                }
                "fragment" -> {
                    val wgslReturn = mapMetalTypeToWGSL(ep.returnType)
                    result += "@fragment\nfn ${ep.name}(${convertParamsToWGSL(ep.params)}) -> $wgslReturn {\n"
                    result += extractAndConvertBody(source, ep.name, "wgsl")
                    result += "}\n\n"
                }
                "kernel" -> {
                    result += "@compute @workgroup_size(1, 1, 1)\nfn ${ep.name}(${convertParamsToWGSL(ep.params)}) {\n"
                    result += extractAndConvertBody(source, ep.name, "wgsl")
                    result += "}\n\n"
                }
            }
        }

        return result
    }

    // --- Metal source parsing helpers ---

    private data class EntryPoint(val type: String, val name: String, val returnType: String, val params: List<Param>)
    private data class Param(val type: String, val name: String, val attribute: String)
    private data class StructInfo(val name: String, val members: List<StructMember>)
    private data class StructMember(val type: String, val name: String, val attribute: String)
    private data class BufferBinding(val type: String, val name: String, val isConst: Boolean)

    private fun detectEntryPoints(source: String): List<EntryPoint> {
        val results = mutableListOf<EntryPoint>()
        val pattern = Regex("""(vertex|fragment|kernel)\s+(\w[\w<>]*)\s+(\w+)\s*\(([^)]*)\)""")
        for (match in pattern.findAll(source)) {
            val qualifier = match.groupValues[1]
            val returnType = match.groupValues[2]
            val name = match.groupValues[3]
            val paramsStr = match.groupValues[4]
            val params = parseParams(paramsStr)
            results.add(EntryPoint(qualifier, name, returnType, params))
        }
        return results
    }

    private fun parseParams(paramsStr: String): List<Param> {
        if (paramsStr.isBlank()) return emptyList()
        return paramsStr.split(",").mapNotNull { paramStr ->
            val trimmed = paramStr.trim()
            val attrMatch = Regex("""\[\[(.+?)]]""").find(trimmed)
            val attribute = attrMatch?.groupValues?.get(1)?.trim() ?: ""
            val cleaned = trimmed.replace(Regex("""\[\[.+?]]"""), "").trim()
            val parts = cleaned.split(Regex("\\s+"))
            if (parts.size >= 2) {
                Param(type = parts.dropLast(1).joinToString(" "), name = parts.last(), attribute = attribute)
            } else null
        }
    }

    private fun detectStructs(source: String): List<StructInfo> {
        val results = mutableListOf<StructInfo>()
        val structPattern = Regex("""struct\s+(\w+)\s*\{([^}]*)}""", RegexOption.DOT_MATCHES_ALL)
        for (match in structPattern.findAll(source)) {
            val name = match.groupValues[1]
            val body = match.groupValues[2]
            val members = parseMemberLines(body)
            results.add(StructInfo(name, members))
        }
        return results
    }

    private fun parseMemberLines(body: String): List<StructMember> {
        val members = mutableListOf<StructMember>()
        val linePattern = Regex("""(\w[\w<>]*)\s+(\w+)\s*(\[\[.+?]])?\s*;""")
        for (match in linePattern.findAll(body)) {
            val type = match.groupValues[1]
            val memberName = match.groupValues[2]
            val attribute = match.groupValues[3]
                .removePrefix("[[").removeSuffix("]]").trim()
            members.add(StructMember(type, memberName, attribute))
        }
        return members
    }

    private fun detectBufferBindings(source: String): List<BufferBinding> {
        val results = mutableListOf<BufferBinding>()
        val pattern = Regex("""(const\s+)?device\s+(\w[\w<>*&]*)\s*[*&]?\s+(\w+)\s*\[\[buffer""")
        for (match in pattern.findAll(source)) {
            val isConst = match.groupValues[1].isNotBlank()
            val type = match.groupValues[2]
            val name = match.groupValues[3]
            results.add(BufferBinding(type, name, isConst))
        }
        return results
    }

    private fun extractAndConvertBody(source: String, functionName: String, target: String): String {
        val funcPattern = Regex("""(?:vertex|fragment|kernel)\s+\w[\w<>]*\s+${Regex.escape(functionName)}\s*\([^)]*\)\s*\{""")
        val matchResult = funcPattern.find(source) ?: return "    // Function body could not be extracted\n"
        val startIdx = matchResult.range.last + 1
        var depth = 1
        var idx = startIdx
        while (idx < source.length && depth > 0) {
            when (source[idx]) {
                '{' -> depth++
                '}' -> depth--
            }
            idx++
        }
        val bodyContent = source.substring(startIdx, (idx - 1).coerceAtLeast(startIdx)).trim()
        if (bodyContent.isEmpty()) return "    // Empty function body\n"

        val converted = when (target) {
            "hlsl" -> applyHLSLTypeReplacements(applyHLSLFunctionReplacements(bodyContent))
            "wgsl" -> applyWGSLReplacements(bodyContent)
            else -> bodyContent
        }
        return converted.lines().joinToString("\n") { "    $it" } + "\n"
    }

    // --- Type mapping tables ---

    private fun mapMetalTypeToSPIRV(type: String): String = when (type) {
        "float" -> "%float"
        "float2" -> "%v2float"
        "float3" -> "%v3float"
        "float4" -> "%v4float"
        "float4x4" -> "%mat4v4float"
        "int" -> "%int"
        "uint" -> "%uint"
        "uint3" -> "%v3uint"
        "half" -> "%float"
        "half4" -> "%v4float"
        else -> "%${type}"
    }

    private fun mapMetalTypeToHLSL(type: String): String = when (type) {
        "float2" -> "float2"
        "float3" -> "float3"
        "float4" -> "float4"
        "float4x4" -> "float4x4"
        "half" -> "min16float"
        "half2" -> "min16float2"
        "half3" -> "min16float3"
        "half4" -> "min16float4"
        "uint" -> "uint"
        "uint2" -> "uint2"
        "uint3" -> "uint3"
        "int" -> "int"
        "bool" -> "bool"
        "texture2d" -> "Texture2D"
        "sampler" -> "SamplerState"
        else -> type
    }

    private fun mapMetalTypeToWGSL(type: String): String = when (type) {
        "float" -> "f32"
        "float2" -> "vec2<f32>"
        "float3" -> "vec3<f32>"
        "float4" -> "vec4<f32>"
        "float4x4" -> "mat4x4<f32>"
        "half" -> "f16"
        "half2" -> "vec2<f16>"
        "half3" -> "vec3<f16>"
        "half4" -> "vec4<f16>"
        "int" -> "i32"
        "uint" -> "u32"
        "uint2" -> "vec2<u32>"
        "uint3" -> "vec3<u32>"
        "bool" -> "bool"
        "texture2d" -> "texture_2d<f32>"
        "sampler" -> "sampler"
        else -> type
    }

    private fun mapMetalAttributeToHLSLSemantic(attribute: String): String = when {
        attribute.startsWith("position") -> "SV_Position"
        attribute.startsWith("stage_in") -> ""
        attribute.startsWith("color(") -> "SV_Target${attribute.removePrefix("color(").removeSuffix(")")}"
        Regex("""buffer\(\d+\)""").matches(attribute) -> ""
        Regex("""texture\(\d+\)""").matches(attribute) -> "register(t${attribute.removePrefix("texture(").removeSuffix(")")})"
        Regex("""sampler\(\d+\)""").matches(attribute) -> "register(s${attribute.removePrefix("sampler(").removeSuffix(")")})"
        else -> attribute
    }

    private fun mapMetalAttributeToWGSLBuiltin(attribute: String): String = when {
        attribute == "position" -> "@builtin(position)"
        attribute.startsWith("vertex_id") -> "@builtin(vertex_index)"
        attribute.startsWith("instance_id") -> "@builtin(instance_index)"
        attribute.startsWith("thread_position_in_grid") -> "@builtin(global_invocation_id)"
        attribute.startsWith("threadgroup_position_in_grid") -> "@builtin(workgroup_id)"
        attribute.startsWith("thread_position_in_threadgroup") -> "@builtin(local_invocation_id)"
        else -> ""
    }

    private fun applyHLSLTypeReplacements(code: String): String {
        var result = code
        result = result.replace(Regex("""\bfloat4x4\b"""), "float4x4")
        result = result.replace(Regex("""\bhalf\b"""), "min16float")
        result = result.replace(Regex("""\bhalf([234])\b"""), "min16float$1")
        result = result.replace(Regex("""\btexture2d<[^>]+>"""), "Texture2D")
        result = result.replace(Regex("""\bsampler\b"""), "SamplerState")
        return result
    }

    private fun applyHLSLFunctionReplacements(code: String): String {
        var result = code
        result = result.replace(Regex("""\bmix\b"""), "lerp")
        result = result.replace(Regex("""\bfract\b"""), "frac")
        result = result.replace(Regex("""\bmetal::"""), "")
        result = result.replace(Regex("""\bdiscard_fragment\s*\(\)"""), "discard")
        result = result.replace(Regex("""\bsample\s*\("""), "Sample(")
        return result
    }

    private fun applyWGSLReplacements(code: String): String {
        var result = code
        result = result.replace(Regex("""\bfloat4x4\b"""), "mat4x4<f32>")
        result = result.replace(Regex("""\bfloat4\b"""), "vec4<f32>")
        result = result.replace(Regex("""\bfloat3\b"""), "vec3<f32>")
        result = result.replace(Regex("""\bfloat2\b"""), "vec2<f32>")
        result = result.replace(Regex("""\bfloat\b"""), "f32")
        result = result.replace(Regex("""\bhalf\b"""), "f16")
        result = result.replace(Regex("""\bint\b"""), "i32")
        result = result.replace(Regex("""\buint\b"""), "u32")
        result = result.replace(Regex("""\bmix\b"""), "mix")
        result = result.replace(Regex("""\bfract\b"""), "fract")
        result = result.replace(Regex("""\bdiscard_fragment\s*\(\)"""), "discard")
        result = result.replace(Regex("""\breturn\b"""), "return")
        return result
    }

    private fun convertParamsToHLSL(params: List<Param>): String {
        return params.filter { it.attribute != "stage_in" }.joinToString(", ") { param ->
            val hlslType = mapMetalTypeToHLSL(param.type)
            val semantic = mapMetalAttributeToHLSLSemantic(param.attribute)
            val semanticStr = if (semantic.isNotEmpty()) " : $semantic" else ""
            "$hlslType ${param.name}$semanticStr"
        }
    }

    private fun convertParamsToWGSL(params: List<Param>): String {
        return params.joinToString(", ") { param ->
            val wgslType = mapMetalTypeToWGSL(param.type)
            val builtin = mapMetalAttributeToWGSLBuiltin(param.attribute)
            val annotation = if (builtin.isNotEmpty()) "$builtin " else ""
            "${annotation}${param.name}: $wgslType"
        }
    }
    
    private fun transpile(sourceFile: VirtualFile, targetExtension: String, targetName: String, 
                         converter: (String) -> String) {
        try {
            val content = String(sourceFile.contentsToByteArray())
            val transpiled = converter(content)
            
            val outputFileName = sourceFile.nameWithoutExtension + "." + targetExtension
            val outputFile = sourceFile.parent?.findChild(outputFileName) 
                ?: WriteAction.compute<VirtualFile, IOException> {
                    sourceFile.parent?.createChildData(this, outputFileName)
                }
            
            WriteAction.run<IOException> {
                outputFile?.setBinaryContent(transpiled.toByteArray())
            }
            
            if (outputFile != null) {
                FileEditorManager.getInstance(project).openFile(outputFile, true)
                Messages.showInfoMessage(
                    project,
                    "Successfully transpiled to $targetName:\n${outputFile.path}",
                    "Transpilation Complete"
                )
            }
        } catch (e: Exception) {
            Messages.showErrorDialog(
                project,
                "Failed to transpile shader:\n${e.message}",
                "Transpilation Error"
            )
        }
    }
}
