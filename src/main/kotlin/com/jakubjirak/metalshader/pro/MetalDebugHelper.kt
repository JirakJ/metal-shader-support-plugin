package com.jakubjirak.metalshader.pro

/**
 * Debug instrumentation for Metal shaders
 */
class MetalDebugHelper {
    
    data class DebugInstrumentation(
        val instrumentedCode: String,
        val debugPoints: List<DebugPoint>
    )
    
    data class DebugPoint(
        val id: Int,
        val line: Int,
        val variable: String,
        val type: String
    )
    
    /**
     * Instrument shader with debug output
     */
    fun instrumentShader(
        shaderCode: String,
        debugVariables: List<String> = emptyList()
    ): DebugInstrumentation? {
        val lines = shaderCode.lines().toMutableList()
        val debugPoints = mutableListOf<DebugPoint>()
        var debugId = 0
        
        // Find function entry points
        val functionPattern = Regex("(kernel|vertex|fragment)\\s+\\w+\\s+\\w+\\s*\\([^)]*\\)")
        lines.forEachIndexed { idx, line ->
            if (functionPattern.containsMatchIn(line)) {
                // Add debug buffer parameter if not exists
                if (!shaderCode.contains("debug_buffer")) {
                    val insertIdx = line.lastIndexOf(')')
                    if (insertIdx != -1) {
                        lines[idx] = line.substring(0, insertIdx) + 
                            ", device float* debug_buffer [[buffer(31)]]" +
                            line.substring(insertIdx)
                    }
                }
            }
        }
        
        // Add debug outputs for specified variables
        if (debugVariables.isNotEmpty()) {
            lines.forEachIndexed { idx, line ->
                debugVariables.forEach { varName ->
                    if (line.contains(varName) && !line.trim().startsWith("//")) {
                        // Add debug write after variable assignment
                        if (line.contains("=") && line.contains(varName)) {
                            val indent = line.takeWhile { it.isWhitespace() }
                            val debugLine = "${indent}debug_buffer[$debugId] = $varName; // DEBUG"
                            lines.add(idx + 1, debugLine)
                            
                            debugPoints.add(DebugPoint(
                                id = debugId++,
                                line = idx + 1,
                                variable = varName,
                                type = "unknown"
                            ))
                        }
                    }
                }
            }
        }
        
        return DebugInstrumentation(
            instrumentedCode = lines.joinToString("\n"),
            debugPoints = debugPoints
        )
    }
    
    /**
     * Generate visualization shader for texture output
     */
    fun generateTextureVisualizer(textureName: String = "debugTexture"): String {
        return """
// Metal Debug Visualizer
// Generated by Metal Shader Support Pro
kernel void visualize_texture(
    texture2d<float, access::read> $textureName [[texture(0)]],
    texture2d<float, access::write> outputTexture [[texture(1)]],
    uint2 gid [[thread_position_in_grid]]
) {
    if (gid.x >= outputTexture.get_width() || gid.y >= outputTexture.get_height()) {
        return;
    }
    
    float4 color = $textureName.read(gid);
    
    // Visualize different channels
    // R channel: Red
    // G channel: Green  
    // B channel: Blue
    // A channel: Grayscale
    
    // You can modify this to visualize specific values
    outputTexture.write(color, gid);
}

kernel void visualize_heatmap(
    texture2d<float, access::read> $textureName [[texture(0)]],
    texture2d<float, access::write> outputTexture [[texture(1)]],
    uint2 gid [[thread_position_in_grid]]
) {
    if (gid.x >= outputTexture.get_width() || gid.y >= outputTexture.get_height()) {
        return;
    }
    
    float value = $textureName.read(gid).r; // Read first channel
    
    // Heatmap: Blue (low) -> Green -> Yellow -> Red (high)
    float4 color;
    if (value < 0.25) {
        color = float4(0, 0, value * 4.0, 1.0);
    } else if (value < 0.5) {
        color = float4(0, (value - 0.25) * 4.0, 1.0, 1.0);
    } else if (value < 0.75) {
        color = float4((value - 0.5) * 4.0, 1.0, 1.0 - (value - 0.5) * 4.0, 1.0);
    } else {
        color = float4(1.0, 1.0 - (value - 0.75) * 4.0, 0, 1.0);
    }
    
    outputTexture.write(color, gid);
}

kernel void visualize_differences(
    texture2d<float, access::read> texture1 [[texture(0)]],
    texture2d<float, access::read> texture2 [[texture(1)]],
    texture2d<float, access::write> outputTexture [[texture(2)]],
    uint2 gid [[thread_position_in_grid]]
) {
    if (gid.x >= outputTexture.get_width() || gid.y >= outputTexture.get_height()) {
        return;
    }
    
    float4 color1 = texture1.read(gid);
    float4 color2 = texture2.read(gid);
    
    float4 diff = abs(color1 - color2);
    float magnitude = length(diff);
    
    // Visualize differences in red
    float4 color = float4(magnitude, 0, 0, 1.0);
    outputTexture.write(color, gid);
}
        """.trimIndent()
    }
    
    /**
     * Generate performance counter shader
     */
    fun generatePerformanceCounters(): String {
        return """
// Metal Performance Counters
// Generated by Metal Shader Support Pro

struct PerformanceStats {
    uint invocations;
    uint cycles_estimate;
    float avg_time_ms;
};

kernel void benchmark_kernel(
    texture2d<float, access::read> input [[texture(0)]],
    texture2d<float, access::write> output [[texture(1)]],
    device PerformanceStats* stats [[buffer(0)]],
    uint2 gid [[thread_position_in_grid]],
    uint2 grid_size [[threads_per_grid]]
) {
    if (gid.x >= output.get_width() || gid.y >= output.get_height()) {
        return;
    }
    
    // Atomic increment invocation counter
    atomic_fetch_add_explicit(
        (device atomic_uint*)&stats->invocations,
        1,
        memory_order_relaxed
    );
    
    // Your shader code here
    float4 color = input.read(gid);
    
    // Simple processing
    color = color * 2.0f;
    
    output.write(color, gid);
}
        """.trimIndent()
    }
    
    /**
     * Generate assert helper functions
     */
    fun generateAssertHelpers(): String {
        return """
// Metal Debug Assertions
// Generated by Metal Shader Support Pro

// Assert that value is in range
inline bool assert_range(float value, float min, float max, 
                         device atomic_uint* error_count) {
    if (value < min || value > max) {
        atomic_fetch_add_explicit(error_count, 1, memory_order_relaxed);
        return false;
    }
    return true;
}

// Assert that texture coordinate is valid
inline bool assert_texture_coord(float2 coord, texture2d<float> tex,
                                  device atomic_uint* error_count) {
    if (coord.x < 0 || coord.x >= tex.get_width() ||
        coord.y < 0 || coord.y >= tex.get_height()) {
        atomic_fetch_add_explicit(error_count, 1, memory_order_relaxed);
        return false;
    }
    return true;
}

// Assert non-NaN value
inline bool assert_finite(float value, device atomic_uint* error_count) {
    if (isnan(value) || isinf(value)) {
        atomic_fetch_add_explicit(error_count, 1, memory_order_relaxed);
        return false;
    }
    return true;
}
        """.trimIndent()
    }
}
